export function isReadOnlyTool(name) {
  return typeof name === "string" && READ_ONLY_TOOLS.has(name);
}

/**
 * Filter a tools/list result whether the MCP server returned one JSON-RPC
 * response or a JSON-RPC batch response.
 */
export function filterToolsListPayload(payload) {
  const filterOne = (item) => {
    if (item && typeof item === "object" && !Array.isArray(item)
        && Array.isArray(item.result?.tools)) {
      return {
        ...item,
        result: {
          ...item.result,
          tools: item.result.tools.filter((tool) => isReadOnlyTool(tool?.name)),
        },
      };
    }
    return item;
  };
  return Array.isArray(payload) ? payload.map(filterOne) : filterOne(payload);
}
